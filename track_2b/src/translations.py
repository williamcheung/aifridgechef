def get_labels(language: str = DEFAULT_LANGUAGE) -> dict[str, str]:
    ''' Return the label dict for the given language, falling back to English
    for an unknown language or any key missing from that language. '''
    english = TRANSLATIONS[DEFAULT_LANGUAGE]
    selected = TRANSLATIONS.get(language, english)
    if selected is english:
        return english
    # Fill any gaps in a partial translation with the English label.
    return {**english, **selected}
